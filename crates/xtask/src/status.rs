//! `cargo xtask status [--check]` (AG-17): writes `docs/status.md` from
//! `docs/features.toml`, after checking that every grade is known, every
//! verified or partial feature names a test, every named test exists and
//! every requirement id is in `docs/requirements.md`.

use std::fmt::Write as _;
use std::path::Path;

use serde::Deserialize;

pub const GRADES: &[(&str, &str)] = &[
    (
        "verified",
        "checked against an exact or independent reference by a named test",
    ),
    ("partial", "works on the named fixtures, with known gaps"),
    ("unverified", "built, not yet checked"),
    ("open", "not built"),
];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Features {
    feature: Vec<Feature>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Feature {
    id: String,
    title: String,
    requirements: Vec<String>,
    grade: String,
    how: String,
    tests: Vec<String>,
    commands: Vec<String>,
    gaps: String,
}

/// Check `features.toml` and render the status page, or list every error.
pub fn render(root: &Path) -> Result<String, Vec<String>> {
    let text = std::fs::read_to_string(root.join("docs/features.toml"))
        .map_err(|e| vec![format!("cannot read docs/features.toml: {e}")])?;
    let features: Features =
        toml::from_str(&text).map_err(|e| vec![format!("docs/features.toml: {e}")])?;
    let requirements =
        std::fs::read_to_string(root.join("docs/requirements.md")).unwrap_or_default();
    let mut errors = Vec::new();
    let mut ids = std::collections::BTreeSet::new();
    for f in &features.feature {
        if !ids.insert(f.id.as_str()) {
            errors.push(format!("{}: the id is repeated", f.id));
        }
        if !GRADES.iter().any(|(g, _)| *g == f.grade) {
            errors.push(format!("{}: unknown grade {}", f.id, f.grade));
        }
        if matches!(f.grade.as_str(), "verified" | "partial") {
            if f.tests.is_empty() {
                errors.push(format!(
                    "{}: a {} feature names at least one test",
                    f.id, f.grade
                ));
            }
            if f.how.trim().is_empty() {
                errors.push(format!(
                    "{}: a {} feature says how it was checked",
                    f.id, f.grade
                ));
            }
        }
        if f.grade == "partial" && f.gaps.trim().is_empty() {
            errors.push(format!("{}: a partial feature names its gaps", f.id));
        }
        for test in &f.tests {
            if let Err(e) = test_exists(root, test) {
                errors.push(format!("{}: {e}", f.id));
            }
        }
        for r in &f.requirements {
            if !requirements.contains(&format!("| {r} |"))
                && !requirements.contains(&format!("| **{r}** |"))
            {
                errors.push(format!(
                    "{}: requirement {r} is not in docs/requirements.md",
                    f.id
                ));
            }
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    Ok(page(&features.feature))
}

fn test_exists(root: &Path, test: &str) -> Result<(), String> {
    let Some((file, name)) = test.split_once("::") else {
        return Err(format!("test {test} is not path::function"));
    };
    let source = std::fs::read_to_string(root.join(file))
        .map_err(|e| format!("test {test}: cannot read {file}: {e}"))?;
    // the function must be a test: `#[test]` within the lines before it
    let lines: Vec<&str> = source.lines().collect();
    let found = lines.iter().enumerate().any(|(i, l)| {
        l.trim_start().starts_with(&format!("fn {name}("))
            && lines[i.saturating_sub(3)..i]
                .iter()
                .any(|p| p.trim() == "#[test]")
    });
    if found {
        Ok(())
    } else {
        Err(format!(
            "test {test} does not exist (no #[test] fn {name} in {file})"
        ))
    }
}

fn cell(s: &str) -> String {
    let s = s.trim().replace('|', "\\|");
    if s.is_empty() { "—".into() } else { s }
}

fn page(features: &[Feature]) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# KoflCraft status\n\n<!-- Generated by `cargo xtask status` from docs/features.toml. Do not edit. -->\n\nThe verification grade of every feature (AG-17), how it was checked and what is still missing. A partial result is never presented as success; every tool result also carries a `limitations` list.\n"
    );
    for (g, meaning) in GRADES {
        let n = features.iter().filter(|f| f.grade == *g).count();
        let _ = writeln!(out, "- **{g}** ({n}): {meaning}");
    }
    let _ = writeln!(
        out,
        "\n| Feature | Grade | How it was checked | Gaps | Requirements |\n|---|---|---|---|---|"
    );
    for f in features {
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            cell(&f.title),
            f.grade,
            cell(&f.how),
            cell(&f.gaps),
            f.requirements.join(", ")
        );
    }
    let _ = writeln!(out, "\n## Checks per feature\n");
    for f in features
        .iter()
        .filter(|f| !f.tests.is_empty() || !f.commands.is_empty())
    {
        let _ = writeln!(out, "### {}\n", f.title);
        for t in &f.tests {
            let (file, name) = t.split_once("::").unwrap_or((t, ""));
            let _ = writeln!(out, "- `{name}` in [{file}](../{file})");
        }
        for c in &f.commands {
            let _ = writeln!(out, "- `{c}` (CI)");
        }
        let _ = writeln!(out);
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
