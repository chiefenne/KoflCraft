//! `docs/tools.md`, generated from the registry (`kofl commands --markdown`).

use std::fmt::Write;

use crate::{CODES, TOOLS};

fn fields(schema: &serde_json::Value) -> String {
    if let Some(variants) = schema["anyOf"].as_array() {
        return variants
            .iter()
            .enumerate()
            .map(|(i, v)| format!("Form {}:\n\n{}", i + 1, fields(v)))
            .collect::<Vec<_>>()
            .join("\n");
    }
    let Some(props) = schema["properties"].as_object() else {
        return "No fields.\n".to_string();
    };
    if props.is_empty() {
        return "No fields.\n".to_string();
    }
    let required: Vec<&str> = schema["required"]
        .as_array()
        .map(|a| a.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();
    let mut s = String::from("| Field | Required | Schema |\n|---|---|---|\n");
    for (name, p) in props {
        let short = match (&p["type"], &p["enum"], &p["const"]) {
            (_, serde_json::Value::Array(e), _) => format!(
                "one of {}",
                e.iter()
                    .map(|v| format!("`{}`", v.as_str().unwrap_or("")))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            (_, _, c) if !c.is_null() => format!("`{c}`"),
            (serde_json::Value::String(t), _, _) => t.clone(),
            (t, _, _) if !t.is_null() => t.to_string(),
            _ => "object".to_string(),
        };
        let _ = writeln!(
            s,
            "| `{name}` | {} | {short} |",
            if required.contains(&name.as_str()) {
                "yes"
            } else {
                "no"
            }
        );
    }
    s
}

/// The tool catalogue and the diagnostic codes as Markdown.
pub fn markdown() -> String {
    let mut s = String::from(
        "# Tools\n\nGenerated by `kofl commands --markdown` from the tool registry (AG-12, crate `mesh-tools`); do not edit by hand. Every engine operation is a tool with a stable id, a contract version, a JSON input and output and an action kind: `read` reads and computes, `write-files` writes new files, `start-build` builds a mesh and writes it. `kofl commands` prints this catalogue as JSON (`koflcraft.tool-catalogue`) with the full schemas; `kofl call <id> --input file.json` runs a tool and prints the result envelope (`koflcraft.tool-result`). Configurations are given inline in the input, files by path.\n\n| Id | Version | Action | Summary |\n|---|---|---|---|\n",
    );
    for t in TOOLS {
        let action = serde_json::to_value(t.action).unwrap_or_default();
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} |",
            t.id,
            t.version,
            action.as_str().unwrap_or(""),
            t.summary
        );
    }
    for t in TOOLS {
        let action = serde_json::to_value(t.action).unwrap_or_default();
        let _ = write!(
            s,
            "\n## `{}`\n\n{}\n\nAction `{}`, version {}{}.\n\n### Input\n\n{}",
            t.id,
            t.summary,
            action.as_str().unwrap_or(""),
            t.version,
            t.legacy_name.map_or(String::new(), |n| format!(
                "; MCP name before the registry `{n}`"
            )),
            fields(&t.input_schema())
        );
        let _ = write!(s, "\n### Output\n\n{}", fields(&t.output_schema()));
    }
    s.push_str("\n## Diagnostic codes\n\n| Code | Name | Severity | Meaning | Fix |\n|---|---|---|---|---|\n");
    for c in CODES {
        let sev = serde_json::to_value(c.severity).unwrap_or_default();
        let _ = writeln!(
            s,
            "| `{}` | `{}` | {} | {} | {} |",
            c.code,
            c.name,
            sev.as_str().unwrap_or(""),
            c.meaning,
            c.fix.unwrap_or("")
        );
    }
    s
}
